typedef struct { const uint8_t *glyphs; uint8_t count; } ChineseTextDef;

static const ChineseTextDef chinese_texts[OLED_TEXT_COUNT] = {
    { text_step, 2U },
    { text_stopwatch, 2U },
    { text_level, 3U },
    { text_flashlight, 3U },
    { text_battery, 2U },
    { text_score, 2U },
    { text_game_over, 4U },
    { text_battery_level, 2U },
    { text_coin, 3U }
};

uint8_t OLED_Chinese_TextWidth(OledChineseTextId text)
{
    if (text >= OLED_TEXT_COUNT)
        return 0U;

    return (uint8_t)(chinese_texts[text].count * OLED_CHINESE_FONT_WIDTH);
}

uint8_t OLED_Chinese_TextWidthSmall(OledChineseTextId text)
{
    return text < OLED_TEXT_COUNT ? (uint8_t)(chinese_texts[text].count * 8U) : 0U;
}

void OLED_Chinese_DrawTextSmall(uint8_t x, uint8_t y,
                                OledChineseTextId text, SSD1306_COLOR color)
{
    if (text >= OLED_TEXT_COUNT) return;
    for (uint8_t c = 0; c < chinese_texts[text].count; c++)
    {
        const uint8_t *glyph = glyph_bytes[chinese_texts[text].glyphs[c]];
        for (uint8_t row = 0; row < 8U; row++)
            for (uint8_t col = 0; col < 8U; col++)
            {
                uint8_t sx = (uint8_t)(col * 2U), sy = (uint8_t)(row * 2U);
                if ((glyph[sy * 2U + sx / 8U] & (uint8_t)(0x80U >> (sx % 8U))) != 0U)
                    ssd1306_DrawPixel((uint8_t)(x + c * 8U + col), (uint8_t)(y + row), color);
            }
    }
}

void OLED_Chinese_DrawText(uint8_t x, uint8_t y,
                           OledChineseTextId text,
                           SSD1306_COLOR color)
{
    const ChineseTextDef *definition;

    if (text >= OLED_TEXT_COUNT)
        return;

    definition = &chinese_texts[text];

    for (uint8_t character = 0; character < definition->count; character++)
    {
        const uint8_t *glyph = glyph_bytes[definition->glyphs[character]];

        for (uint8_t row = 0; row < OLED_CHINESE_FONT_HEIGHT; row++)
        {
            for (uint8_t column = 0; column < OLED_CHINESE_FONT_WIDTH; column++)
            {
                uint16_t pixel_x = (uint16_t)x + character * OLED_CHINESE_FONT_WIDTH + column;
                uint16_t pixel_y = (uint16_t)y + row;
                uint8_t byte = glyph[row * 2U + column / 8U];
                uint8_t mask = (uint8_t)(0x80U >> (column % 8U));

                if ((byte & mask) != 0U &&
                    pixel_x < SSD1306_WIDTH && pixel_y < SSD1306_HEIGHT)
                {
                    ssd1306_DrawPixel((uint8_t)pixel_x, (uint8_t)pixel_y, color);
                }
            }
        }
    }
}
